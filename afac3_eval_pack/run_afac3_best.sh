#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AFAC_ROOT="${AFAC_ROOT:-/home/cyp/speedsci/AFAC2026}"
V1_FRAMEWORK="${V1_FRAMEWORK:-${AFAC_ROOT}/v1/framework}"

cd "${ROOT}"

echo "===== AFAC-3 eval pack ====="
echo "ROOT=${ROOT}"
echo "V1_FRAMEWORK=${V1_FRAMEWORK}"
date

mkdir -p A分类 A推荐
rm -f A分类/A分类 A推荐/A推荐
ln -s "${V1_FRAMEWORK}/data/cls_data" A分类/A分类
ln -s "${V1_FRAMEWORK}/data/rec_data" A推荐/A推荐

echo "===== Check dependencies ====="
python - <<'PY'
import numpy, pandas, scipy, sklearn, torch
print("basic deps ok")
try:
    import xgboost
    print("xgboost ok")
except Exception as e:
    print("xgboost unavailable:", e)
PY

echo "===== Task1: train_cls.py ====="
python train_cls.py 2>&1 | tee train_cls.log

echo "===== Task1: predict_cls_deg.py ====="
python predict_cls_deg.py 2>&1 | tee predict_cls_deg.log

echo "===== Task2: train_task_b_final.py ====="
python train_task_b_final.py 2>&1 | tee train_task_b_final.log

echo "===== Package ====="
test -f A1.csv
test -f A2.csv
rm -f prediction_afac3.zip
zip prediction_afac3.zip A1.csv A2.csv
ls -lh prediction_afac3.zip

echo "===== Copy to v1/framework/output_afac3 ====="
mkdir -p "${V1_FRAMEWORK}/output_afac3/submission"
cp A1.csv "${V1_FRAMEWORK}/output_afac3/submission/A1.csv"
cp A2.csv "${V1_FRAMEWORK}/output_afac3/submission/A2.csv"
cp prediction_afac3.zip "${V1_FRAMEWORK}/output_afac3/prediction.zip"

cat > "${V1_FRAMEWORK}/output_afac3/README_result.txt" <<EOF
Generated by AFAC-3 eval pack.
Task1:
- train_cls.py
- predict_cls_deg.py
Task2:
- train_task_b_final.py
Files:
- submission/A1.csv
- submission/A2.csv
- prediction.zip
EOF

echo "===== Done ====="
ls -lh "${V1_FRAMEWORK}/output_afac3/prediction.zip"
date
